package com.kraken.api.service.walker.transport.registry;

import com.google.gson.Gson;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParseException;
import com.kraken.api.service.walker.transport.ObjectInfo;
import com.kraken.api.util.JsonResourceUtils;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.runelite.api.coords.WorldPoint;

import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.HashSet;
import java.util.IdentityHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * The transports of the game world that ship with the API: every door, ladder, shortcut, boat,
 * teleport and hub network the walker plans through before anyone registers anything.
 *
 * <p>The data lives in {@code src/main/resources/walker/dataset.json}. It is generated by
 * {@code scripts/update_walker_transports.py} from the transport files of the
 * <a href="https://github.com/Skretzo/shortest-path">shortest-path</a> project, so it is
 * regenerated and never edited by hand. A correction to one of its transports is a row of
 * {@code walker/transports.json} that sets {@code replaces}.</p>
 *
 * <p>The file has two parts. {@code transports} holds one row per transport, in the format
 * {@link BundledTransports} reads. {@code hubs} holds the networks whose every stop leads to every
 * other, such as fairy rings: a hub lists its stops once, and they are paired up here, so 55 fairy
 * rings are 110 rows in the file and some three thousand transports in memory.</p>
 *
 * <p>Reading the file takes a moment, so it is read once, the first time a search needs it, and
 * shared from then on.</p>
 */
@Slf4j
@NoArgsConstructor(access = AccessLevel.PRIVATE)
public final class TransportDataset {

    /** Where the dataset is read from on the classpath. */
    public static final String RESOURCE_PATH = "/walker/dataset.json";

    private static final Gson GSON = new Gson();

    private static final Set<String> ROOT_KEYS = Set.of("source", "transports", "hubs");
    private static final Set<String> HUB_KEYS = Set.of(
            "id", "category", "minDistance", "requirements", "origins", "destinations");
    private static final Set<String> STOP_KEYS = Set.of(
            "origin", "destination", "menuOption", "menuTarget", "entityId", "objectInfo", "displayInfo",
            "duration", "consumable", "requirements");

    /**
     * Returns the bundled dataset, reading it on first use. A missing or unreadable file yields no
     * transports instead of an exception, so the walker can still walk.
     *
     * @return every transport of the dataset, in file order with each hub's pairs after the rows
     */
    public static List<TransportDefinition> bundled() {
        return Bundled.DEFINITIONS;
    }

    /**
     * Parses a dataset from JSON text.
     *
     * @param json the text of a dataset file
     * @return what was read, and what could not be
     * @throws JsonParseException when the text is not a JSON object
     */
    public static Result parse(String json) {
        return read(GSON.fromJson(json, JsonObject.class));
    }

    private static Result read(JsonObject root) {
        List<TransportDefinition> definitions = new ArrayList<>();
        List<String> problems = new ArrayList<>();
        if (root == null) {
            return new Result(definitions, problems);
        }

        for (String key : root.keySet()) {
            if (!ROOT_KEYS.contains(key)) {
                problems.add("unknown key '" + key + "' in the dataset");
            }
        }

        JsonArray rows = root.has("transports") ? root.getAsJsonArray("transports") : new JsonArray();
        for (JsonElement row : rows) {
            try {
                definitions.add(BundledTransports.toDefinition(row, false));
            } catch (IllegalArgumentException | JsonParseException e) {
                problems.add(e.getMessage());
            }
        }

        Set<String> ids = new HashSet<>();
        definitions.forEach(definition -> ids.add(definition.getId()));

        JsonArray hubs = root.has("hubs") ? root.getAsJsonArray("hubs") : new JsonArray();
        for (JsonElement hub : hubs) {
            try {
                expand(hub.getAsJsonObject(), ids, definitions, problems);
            } catch (IllegalArgumentException | IllegalStateException | ClassCastException | JsonParseException e) {
                problems.add("hub could not be read: " + e.getMessage());
            }
        }

        return new Result(Collections.unmodifiableList(definitions), Collections.unmodifiableList(problems));
    }

    /**
     * Pairs every origin stop of a hub with every destination stop far enough away, and adds one
     * transport per pair.
     *
     * <p>A pair is clicked the way its origin stop says and chooses the destination its other stop
     * names. It needs what the hub, the origin and the destination each ask for, and takes as long
     * as the slower of its two stops.</p>
     */
    private static void expand(JsonObject hub, Set<String> ids, List<TransportDefinition> definitions,
                               List<String> problems) {
        String hubId = hub.has("id") ? hub.get("id").getAsString() : null;
        if (hubId == null || hubId.trim().isEmpty()) {
            throw new IllegalArgumentException("a hub needs an id");
        }
        requireKnownKeys(hubId, hub, HUB_KEYS);

        TransportCategory category = GSON.fromJson(hub.get("category"), TransportCategory.class);
        if (category == null) {
            throw new IllegalArgumentException(hubId + ": unknown category " + hub.get("category"));
        }
        int minDistance = hub.has("minDistance") ? hub.get("minDistance").getAsInt() : 0;
        DefinitionRequirements shared = BundledTransports.toRequirements(hubId, hub.get("requirements"));

        // Stops that ask for the same thing share one requirements object, and so do the pairs
        // built from them. A search remembers its verdict per object, so thousands of pairs cost
        // it a few dozen checks.
        Map<String, DefinitionRequirements> interned = new HashMap<>();
        List<Stop> origins = readStops(hubId, hub.getAsJsonArray("origins"), true, interned, problems);
        List<Stop> destinations = readStops(hubId, hub.getAsJsonArray("destinations"), false, interned, problems);
        Map<DefinitionRequirements, Map<DefinitionRequirements, DefinitionRequirements>> joined = new IdentityHashMap<>();

        for (Stop origin : origins) {
            DefinitionRequirements fromOrigin = shared.and(origin.requirements);
            Map<DefinitionRequirements, DefinitionRequirements> withDestination =
                    joined.computeIfAbsent(origin.requirements, key -> new IdentityHashMap<>());
            for (Stop destination : destinations) {
                if (origin.tile.distanceTo2D(destination.tile) <= minDistance) {
                    continue;
                }

                String id = hubId + "-" + key(origin.tile) + "-to-" + key(destination.tile);
                for (int copy = 2; !ids.add(id); copy++) {
                    id = hubId + "-" + key(origin.tile) + "-to-" + key(destination.tile) + "-" + copy;
                }

                try {
                    definitions.add(TransportDefinition.builder()
                            .id(id)
                            .origin(origin.tile)
                            .destination(destination.tile)
                            .category(category)
                            .menuOption(origin.menuOption)
                            .menuTarget(origin.menuTarget)
                            .entityId(origin.entityId)
                            .objectInfo(origin.objectInfo)
                            .displayInfo(destination.displayInfo)
                            .duration(Math.max(origin.duration, destination.duration))
                            .consumable(origin.consumable || destination.consumable)
                            .requirements(withDestination.computeIfAbsent(destination.requirements, fromOrigin::and))
                            .build());
                } catch (IllegalArgumentException e) {
                    problems.add(e.getMessage());
                }
            }
        }
    }

    private static List<Stop> readStops(String hubId, JsonArray rows, boolean origins,
                                        Map<String, DefinitionRequirements> interned, List<String> problems) {
        List<Stop> stops = new ArrayList<>();
        if (rows == null) {
            return stops;
        }

        String tileKey = origins ? "origin" : "destination";
        for (JsonElement element : rows) {
            try {
                JsonObject row = element.getAsJsonObject();
                requireKnownKeys(hubId, row, STOP_KEYS);
                if (!row.has(tileKey) || row.has(origins ? "destination" : "origin")) {
                    throw new IllegalArgumentException(hubId + ": a stop under " + tileKey + "s names its " + tileKey + " tile only");
                }

                JsonObject tile = row.getAsJsonObject(tileKey);
                Stop stop = new Stop();
                stop.tile = new WorldPoint(tile.get("x").getAsInt(), tile.get("y").getAsInt(), tile.get("plane").getAsInt());
                stop.menuOption = text(row, "menuOption");
                stop.menuTarget = text(row, "menuTarget");
                stop.entityId = row.has("entityId") ? row.get("entityId").getAsInt() : ObjectInfo.NO_ID;
                stop.objectInfo = text(row, "objectInfo");
                stop.displayInfo = text(row, "displayInfo");
                stop.duration = row.has("duration") ? row.get("duration").getAsInt() : 1;
                stop.consumable = row.has("consumable") && row.get("consumable").getAsBoolean();
                JsonElement requirements = row.get("requirements");
                stop.requirements = requirements == null ? DefinitionRequirements.NONE
                        : interned.computeIfAbsent(requirements.toString(),
                                key -> BundledTransports.toRequirements(hubId, requirements));
                stops.add(stop);
            } catch (IllegalArgumentException | IllegalStateException | ClassCastException | NullPointerException
                     | JsonParseException e) {
                problems.add(hubId + ": a stop could not be read: " + e.getMessage());
            }
        }
        return stops;
    }

    private static String text(JsonObject row, String key) {
        return row.has(key) && !row.get(key).isJsonNull() ? row.get(key).getAsString() : null;
    }

    private static String key(WorldPoint tile) {
        return tile.getX() + "-" + tile.getY() + "-" + tile.getPlane();
    }

    private static void requireKnownKeys(String id, JsonObject json, Set<String> knownKeys) {
        for (Map.Entry<String, JsonElement> entry : json.entrySet()) {
            if (!knownKeys.contains(entry.getKey())) {
                throw new IllegalArgumentException(id + ": unknown key '" + entry.getKey() + "'");
            }
        }
    }

    /** One stop of a hub, as the file writes it. */
    private static final class Stop {
        private WorldPoint tile;
        private String menuOption;
        private String menuTarget;
        private int entityId;
        private String objectInfo;
        private String displayInfo;
        private int duration;
        private boolean consumable;
        private DefinitionRequirements requirements;
    }

    /**
     * What reading a dataset gave.
     */
    @Getter
    public static final class Result {

        /** The transports that were read, hub pairs included. */
        private final List<TransportDefinition> definitions;

        /** One line for each row, stop or hub that could not be read. Empty for a sound file. */
        private final List<String> problems;

        private Result(List<TransportDefinition> definitions, List<String> problems) {
            this.definitions = definitions;
            this.problems = problems;
        }
    }

    /** Holds the bundled dataset, so it is read when first asked for and only once. */
    private static final class Bundled {
        private static final List<TransportDefinition> DEFINITIONS = load();

        private static List<TransportDefinition> load() {
            try {
                long started = System.nanoTime();
                Result result = read(JsonResourceUtils.loadJsonResource(
                        TransportDataset.class, RESOURCE_PATH, GSON, JsonObject.class));
                for (String problem : result.getProblems()) {
                    log.warn("Skipping dataset transport: {}", problem);
                }
                log.info("Loaded {} walker transports from the dataset in {} ms",
                        result.getDefinitions().size(), (System.nanoTime() - started) / 1_000_000);
                return result.getDefinitions();
            } catch (RuntimeException e) {
                // Whatever is wrong with the file, the walker is better off walking than failing
                // every search, so a file that cannot be read at all counts as an empty dataset.
                log.error("Could not read the walker transport dataset from {}", RESOURCE_PATH, e);
                return Collections.emptyList();
            }
        }
    }
}
